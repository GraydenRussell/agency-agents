/**
 * Prints the Supabase pg_cron + pg_net SQL that calls Life OS's scheduled job endpoints.
 *
 *   APP_URL=https://life.example.com CRON_SECRET=... npx tsx scripts/cron-sql.ts > cron.sql
 *
 * Run the output in the Supabase SQL editor (Database → Extensions: enable pg_cron and pg_net first).
 * Re-running is safe: each job is unscheduled before being scheduled again.
 * Phoenix is UTC-7 year-round, so these UTC crons never drift.
 */
import { config } from "dotenv";

config({ path: ".env.local" });
config();

const appUrl = (process.env.APP_URL ?? "").replace(/\/$/, "");
const secret = process.env.CRON_SECRET ?? "";
if (!appUrl.startsWith("https://")) throw new Error("APP_URL must be your public https URL");
if (secret.length < 16) throw new Error("CRON_SECRET must be set (16+ chars)");

const jobs: Array<[name: string, cron: string, note: string]> = [
  ["daily-brief", "0 13 * * *", "6:00 AM Phoenix"],
  ["evening-wrap", "0 4 * * *", "9:00 PM Phoenix"],
  ["weekly-review", "0 1 * * 1", "Sunday 6:00 PM Phoenix (Mon 01:00 UTC)"],
  ["inbox", "*/30 * * * *", "every 30 minutes"],
  ["reminders", "* * * * *", "every minute"],
  ["calendar", "*/10 * * * *", "every 10 minutes"],
  ["projects", "7 * * * *", "hourly"],
  ["housecall", "12,42 * * * *", "every 30 minutes"],
  ["leads", "*/5 * * * *", "every 5 minutes"],
  ["rebook", "0 14 * * 1", "Monday 7:00 AM Phoenix"],
  ["maintenance", "0 10 * * *", "3:00 AM Phoenix"],
];

const esc = (s: string) => s.replace(/'/g, "''");
const lines = [
  "-- Generated by scripts/cron-sql.ts",
  "create extension if not exists pg_cron;",
  "create extension if not exists pg_net;",
  "",
];
for (const [name, cron, note] of jobs) {
  lines.push(
    `-- ${name}: ${note}`,
    `select cron.unschedule('lifeos-${name}') where exists (select 1 from cron.job where jobname = 'lifeos-${name}');`,
    `select cron.schedule('lifeos-${name}', '${cron}', $$select net.http_post(url := '${esc(appUrl)}/api/cron/${name}', headers := jsonb_build_object('x-cron-secret', '${esc(secret)}', 'content-type', 'application/json'), body := '{}'::jsonb, timeout_milliseconds := 290000)$$);`,
    "",
  );
}
lines.push("-- Inspect: select jobname, schedule, active from cron.job; select * from cron.job_run_details order by start_time desc limit 20;");
console.log(lines.join("\n"));
